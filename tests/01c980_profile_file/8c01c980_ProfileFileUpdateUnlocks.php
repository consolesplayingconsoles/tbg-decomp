    private function resolveSymbols(): void
    {
        $this->setSize('_var_profileUnlockedCount_8c2263a4', 4);
        $this->setSize('_var_profileUnlocked_8c2263b4', 56);
        $this->setSize('_EventHasProgressFlagAlt_8c02aff0', 4);
    }

    /**
     * Runs the scan and asserts every call + write in exact execution
     * order. $hitBySlot maps a slot index to the one flag value in that
     * slot's list which should test true (all others in every slot miss).
     */
    private function runScan(array $hitBySlot): void
    {
        $this->resolveSymbols();
        $b4 = $this->addressOf('_var_profileUnlocked_8c2263b4');

        $this->call('_ProfileFileUpdateUnlocks_8c01c980');

        $this->shouldWriteLongTo('_var_profileUnlockedCount_8c2263a4', 0);

        $count = 0;
        foreach (self::SLOTS as $i => $flags) {
            $hitFlag = $hitBySlot[$i] ?? null;
            $hit = false;
            foreach ($flags as $flag) {
                $isHit = $hitFlag !== null && $flag === $hitFlag;
                $this->shouldCall('_EventHasProgressFlagAlt_8c02aff0')
                    ->with($flag)
                    ->andReturn($isHit ? 1 : 0);
                if ($isHit) {
                    $hit = true;
                    break;
                }
            }
            $this->shouldWriteByte($b4 + $i, $hit ? 1 : 0);
            if ($hit) {
                $count++;
                $this->shouldWriteLongTo('_var_profileUnlockedCount_8c2263a4', $count);
            }
        }
    }

    public function test_no_flags_set_unlocks_nothing(): void
    {
        $this->runScan([]);
    }

    public function test_unlocks_on_first_flag_in_list(): void
    {
        // Slot 4's list is [0x3c, 0x3d, 0x3e]; hitting the first flag
        // must stop the scan before 0x3d/0x3e are ever checked.
        $this->runScan([4 => 0x3c]);
    }

    public function test_unlocks_on_later_flag_in_list(): void
    {
        // Slot 0's list is [0x32, 0x33, 0x7c, 0x34, 0x7d, 0x35, 0x7e, 0x3b];
        // hitting 0x35 (index 5) must still miss on the preceding 5 flags
        // and skip the trailing 0x7e/0x3b.
        $this->runScan([0 => 0x35]);
    }

    public function test_tallies_multiple_unlocked_slots_in_order(): void
    {
        $this->runScan([2 => 0x38, 40 => 0x6c]);
    }
};
